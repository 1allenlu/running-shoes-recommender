"""Report catalog gaps: shoes missing specs or fit notes, unverified notes, missing size charts.

    uv run python -m app.ingest.validate_catalog          # report from the database
    uv run python -m app.ingest.validate_catalog --todo   # rewrite data/seed/TODO_VERIFY.md

Exits 1 if any gap is found, so it can gate a release.
"""

import sys
from collections import Counter
from pathlib import Path

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.db.models import FitNote, Shoe, SizeChart
from app.ranking.sizing import REFERENCE_CHART

SPEC_FIELDS = (
    "drop_mm",
    "stack_heel_mm",
    "stack_forefoot_mm",
    "weight_g",
    "widths_available",
    "toe_box",
    "upper_volume",
    "heel_lock",
    "price_usd",
    "toebox_width_mm",
    "toebox_width_bigtoe_mm",
    "forefoot_width_mm",
    "heel_width_mm",
    "upper_stretch",
    "heel_counter",
    "midsole_softness",
    "stability_features",
)
MIN_FIT_NOTES = 3
UNVERIFIED_SOURCE = "draft-unverified"


def find_gaps(session: Session) -> list[str]:
    gaps = []
    notes = session.scalars(select(FitNote)).all()
    note_counts = Counter(n.shoe_id for n in notes)
    unverified = Counter(n.shoe_id for n in notes if n.source == UNVERIFIED_SOURCE)
    chart_brands = set(session.scalars(select(SizeChart.brand).distinct()))

    shoes = session.scalars(select(Shoe).order_by(Shoe.brand, Shoe.model)).all()
    for shoe in shoes:
        name = f"{shoe.brand} {shoe.model} {shoe.version}"
        missing = [field for field in SPEC_FIELDS if getattr(shoe, field) is None]
        if missing:
            gaps.append(f"{name}: missing specs: {', '.join(missing)}")
        if note_counts[shoe.id] < MIN_FIT_NOTES:
            gaps.append(f"{name}: {note_counts[shoe.id]} fit notes (need {MIN_FIT_NOTES})")
        if unverified[shoe.id]:
            gaps.append(f"{name}: {unverified[shoe.id]} fit notes still {UNVERIFIED_SOURCE}")

    if REFERENCE_CHART not in chart_brands:
        gaps.append(f"{REFERENCE_CHART}: no reference size chart (scan size -> foot length)")
    for brand in sorted({s.brand for s in shoes} - chart_brands):
        gaps.append(f"{brand}: no size chart rows loaded")
    return gaps


def todo_verify_markdown(seed_dir: Path) -> str:
    """Owner checklist of every TODO in the seed files (no database needed)."""
    from app.ingest.load_catalog import parse_fit_notes, parse_shoes, parse_size_charts

    shoes = parse_shoes(seed_dir / "shoes.csv")
    lines = [
        "# Specs to verify",
        "",
        "Generated by `uv run python -m app.ingest.validate_catalog --todo`; don't edit by hand.",
        "Fill the values in `shoes.csv` / `size_charts.csv` from brand pages or affiliate feeds",
        "(never review or lab sites), then regenerate.",
        "",
        "## Shoes",
        "",
    ]
    for shoe in shoes:
        missing = [f for f in SPEC_FIELDS if shoe.get(f) is None]
        if missing:
            name = f"{shoe['brand']} {shoe['model']} {shoe['version']}"
            lines.append(f"- [ ] **{name}**: {', '.join(missing)}")

    _, skipped = parse_size_charts(seed_dir / "size_charts.csv")
    brands = sorted({s["brand"] for s in shoes} | {REFERENCE_CHART})
    lines += ["", "## Size charts", "", f"- [ ] {skipped} rows with TODO lengths "
              f"({', '.join(brands)})"]  # fmt: skip

    notes = parse_fit_notes(seed_dir / "fit_notes.jsonl")
    unverified = sum(n["source"] == UNVERIFIED_SOURCE for n in notes)
    lines += ["", "## Fit notes", "", f"- [ ] {unverified} of {len(notes)} notes still "
              f"`{UNVERIFIED_SOURCE}`: check each against a source and set `source`"]  # fmt: skip
    return "\n".join(lines) + "\n"


def main() -> None:
    from app.db.session import SessionLocal

    if "--todo" in sys.argv:
        seed_dir = Path("data/seed")
        (seed_dir / "TODO_VERIFY.md").write_text(todo_verify_markdown(seed_dir))
        print(f"wrote {seed_dir / 'TODO_VERIFY.md'}")
        return

    with SessionLocal() as session:
        gaps = find_gaps(session)
    for gap in gaps:
        print(gap)
    print(f"\n{len(gaps)} gaps found." if gaps else "Catalog complete.")
    sys.exit(1 if gaps else 0)


if __name__ == "__main__":
    main()
